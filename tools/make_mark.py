"""Turns the app icon's gamepad and dots into alpha masks in src/mark_data.h,
so the TV app draws the same logo as the home screen icon.
Needs ImageMagick (convert). Run: python3 tools/make_mark.py"""
import subprocess
from pathlib import Path

N = 128  # mask size; the app scales it to any mark size
GAMEPAD = ("M150 170h212c50 0 76 30 90 90l22 96c8 38-22 64-52 52-20-8-36-34-52-60H142"
           "c-16 26-32 52-52 60-30 12-60-14-52-52l22-96c14-60 40-90 90-90z")
DOTS = '<circle cx="196" cy="268" r="24"/><circle cx="256" cy="268" r="24"/><circle cx="316" cy="268" r="24"/>'

root = Path(__file__).resolve().parent.parent


def mask(shape):
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 512 512">'
           f'<rect width="512" height="512" fill="#000"/><g fill="#fff">{shape}</g></svg>')
    raw = subprocess.run(["convert", "svg:-", "-resize", f"{N}x{N}", "-colorspace", "Gray", "-depth", "8", "gray:-"],
                         input=svg.encode(), capture_output=True, check=True).stdout
    assert len(raw) == N * N, len(raw)
    return raw


def c_array(name, data):
    rows = [", ".join(str(b) for b in data[i:i + 32]) for i in range(0, len(data), 32)]
    return f"static const unsigned char {name}[{len(data)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


out = ["// Copyright (C) 2026 Chokri Hammedi (blue0x1) <https://github.com/blue0x1>. All rights reserved.",
       "// Generated by tools/make_mark.py from the app icon. Do not edit by hand.", "#pragma once", "",
       f"#define MARK_N {N}", "", c_array("MARK_GAMEPAD", mask(f'<path d="{GAMEPAD}"/>')), c_array("MARK_DOTS", mask(DOTS))]
(root / "src" / "mark_data.h").write_text("\n".join(out))
print("wrote src/mark_data.h")
