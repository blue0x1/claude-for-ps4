"""Turns src/web/*.html and *.css into C strings in src/web_assets.h.
Run after editing the phone page: python3 tools/embed_web.py"""
from pathlib import Path

root = Path(__file__).resolve().parent.parent
out = ["// Generated by tools/embed_web.py from src/web/. Do not edit by hand.", "#pragma once", ""]
for f in sorted((root / "src" / "web").iterdir()):
    if f.suffix not in (".html", ".css"):
        continue
    name = "WEB_" + f.stem.upper() + ("_CSS" if f.suffix == ".css" else "_HTML")
    out.append(f"static const char {name}[] =")
    for line in f.read_text().splitlines():
        esc = line.replace("\\", "\\\\").replace('"', '\\"')
        out.append(f'    "{esc}\\n"')
    out.append(";")
    out.append("")
(root / "src" / "web_assets.h").write_text("\n".join(out))
print("wrote src/web_assets.h")
